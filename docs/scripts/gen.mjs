#!/usr/bin/env node
// Generates every piece of reference material from the axx binary, the single
// source of truth (ADR 0005). Run by `npm run build` and `npm run dev`.
//
//   src/content/docs/references/_gen/   step pack pages, the steps overview (with the
//                                      parameter types), all steps, CLI pages,
//                                      error codes
//   public/skills/                     the agent skills (SKILL.md + references)
//   public/.well-known/agent-skills/   index.json listing the skills
//   public/schemas/v0/                 axx.yaml JSON Schema
//
// All outputs are gitignored. The script fails if any of them comes out empty:
// a docs site that silently publishes an empty reference is worse than no build.
//
// Set AXX_BIN to use an existing binary instead of building one with `go build`.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { capitalizeDocsBrand } from './brand-name.mjs';

const docsDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoDir = path.resolve(docsDir, '..');
const genDir = path.join(docsDir, 'src/content/docs/references/_gen');
const publicDir = path.join(docsDir, 'public');
const site = 'https://axx.nimbusxr.us';
const repoUrl = 'https://github.com/nimbusxr/axx';

const log = (msg) => console.log(`gen: ${msg}`);

function fail(msg) {
	console.error(`gen: error: ${msg}`);
	process.exit(1);
}

// ---------------------------------------------------------------- the binary

function resolveBinary() {
	if (process.env.AXX_BIN) {
		const bin = path.resolve(process.env.AXX_BIN);
		if (!fs.existsSync(bin)) fail(`AXX_BIN=${process.env.AXX_BIN} does not exist`);
		return bin;
	}
	// axx with every pack axx publishes: the reference covers all of them.
	const bin = path.join(repoDir, 'bin', process.platform === 'win32' ? 'axx-all.exe' : 'axx-all');
	log('building axx with every pack (go build -o ../bin/axx-all ../internal/tools/axxall)');
	try {
		execFileSync('go', ['build', '-o', path.relative(docsDir, bin), '../internal/tools/axxall'], {
			cwd: docsDir,
			stdio: 'inherit',
			env: { ...process.env, CGO_ENABLED: '0' },
		});
	} catch {
		fail('`go build` failed. Use the Go version from go.mod (`mise exec -- npm run build`) or set AXX_BIN.');
	}
	return bin;
}

const axxBin = resolveBinary();

/** Runs axx with a clean, non-agent environment so output is deterministic. */
function axx(args, { allowFailure = false } = {}) {
	// Help text shows flag defaults, and some defaults come from the environment.
	const env = { ...process.env };
	for (const k of ['NO_COLOR', 'AI_AGENT', 'AGENT', 'CLAUDECODE', 'CODEX_SANDBOX', 'GEMINI_CLI', 'CURSOR_AGENT', 'AXX_PROFILE']) delete env[k];
	try {
		return execFileSync(axxBin, args, { cwd: docsDir, env, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
	} catch (err) {
		if (allowFailure) return err.stdout ?? '';
		fail(`axx ${args.join(' ')} failed:\n${err.stderr || err.message}`);
	}
}

log(axx(['version']).trim());

// ------------------------------------------------------------------ helpers

function reset(p) {
	fs.rmSync(p, { recursive: true, force: true });
}

function write(file, content) {
	fs.mkdirSync(path.dirname(file), { recursive: true });
	fs.writeFileSync(file, content);
}

function listFiles(dir, predicate = () => true) {
	if (!fs.existsSync(dir)) return [];
	return fs
		.readdirSync(dir, { recursive: true, withFileTypes: true })
		.filter((d) => d.isFile() && predicate(d.name))
		.map((d) => path.join(d.parentPath, d.name));
}

/** YAML front matter; JSON strings are valid YAML scalars. */
function frontmatter(fields) {
	const lines = Object.entries(fields).map(([k, v]) =>
		typeof v === 'object' ? `${k}:\n${Object.entries(v).map(([k2, v2]) => `  ${k2}: ${JSON.stringify(v2)}`).join('\n')}` : `${k}: ${JSON.stringify(v)}`,
	);
	return `---\n${lines.join('\n')}\n---\n`;
}

/** Escapes < and > outside inline code so help text is safe in Markdown. */
function escapeProse(text) {
	return text
		.split(/(`[^`]*`)/)
		.map((part, i) => (i % 2 ? part : part.replace(/</g, '&lt;').replace(/>/g, '&gt;')))
		.join('');
}

const GENERATED = (source) => `<!-- Code generated by docs/scripts/gen.mjs from ${source}. DO NOT EDIT. -->\n`;

// ------------------------------------------------- 1. axx docs export

reset(genDir);
log('axx docs export');
axx(['docs', 'export', '--out', genDir]);

// step-index.md is written for grep (skills), without front matter. Give it
// the front matter the site needs and let the page title replace its heading.
{
	const file = path.join(genDir, 'step-index.md');
	if (fs.existsSync(file)) {
		const body = fs.readFileSync(file, 'utf8').replace(/^# Step index\n+/m, '');
		if (!body.startsWith('---')) {
			write(
				file,
				frontmatter({
					title: 'All steps',
					description: 'Every step Axx understands, one per line: pack, id and expression. Search it before writing a step.',
				}) +
					'\n' +
					body.replace('see parameter-types.md', 'see [parameter types](/references/steps/#parameter-types)'),
			);
		}
	}
}

// The steps overview: the grammar every step follows (src/partials/how-steps-read.md)
// followed by the parameter types table from `axx docs export`, which then
// has no page of its own.
{
	const paramsFile = path.join(genDir, 'parameter-types.md');
	const exported = fs.existsSync(paramsFile) ? fs.readFileSync(paramsFile, 'utf8') : '';
	const table = exported.slice(exported.indexOf('\n| Parameter')).trim();
	if (!table.startsWith('| Parameter')) fail('parameter types table not found in parameter-types.md');
	fs.rmSync(paramsFile);
	write(
		path.join(genDir, 'steps', 'index.md'),
		frontmatter({
			title: 'How steps read',
			description: 'The grammar every step of axx\'s packs follows (optional parts, services, ordinals, arguments) and the parameter types.',
		}) +
			'\n' +
			GENERATED('src/partials/how-steps-read.md and `axx docs export`') +
			'\n' +
			fs.readFileSync(path.join(docsDir, 'src/partials/how-steps-read.md'), 'utf8').trimEnd() +
			'\n\n' +
			table +
			'\n',
	);
}

// Pack pages are titled after what they test, not the pack's id.
{
	const titles = {
		rest: 'REST',
		mock: 'Mocks',
		sql: 'SQL',
		mongo: 'MongoDB',
		kafka: 'Kafka',
		logs: 'Logs',
		'aws-core': 'AWS account',
		'aws-s3': 'S3',
		'aws-sqs': 'SQS',
		'aws-sns': 'SNS',
		'aws-eventbridge': 'EventBridge',
		'aws-dynamodb': 'DynamoDB',
		'gcp-core': 'Google Cloud project',
		'gcp-storage': 'Cloud Storage',
		'gcp-pubsub': 'Pub/Sub',
		'gcp-bigquery': 'BigQuery',
		'gcp-firestore': 'Firestore',
		'azure-blob': 'Blob Storage',
		'azure-servicebus': 'Service Bus',
	};
	for (const [pack, title] of Object.entries(titles)) {
		const file = path.join(genDir, 'steps', `${pack}.md`);
		if (!fs.existsSync(file)) continue;
		fs.writeFileSync(file, fs.readFileSync(file, 'utf8').replace(/^title: .*$/m, `title: ${title}`));
	}
}

// ------------------------------------------------- 2. skills

const skillsDir = path.join(publicDir, 'skills');
reset(skillsDir);
log('axx skills export');
axx(['skills', 'export', '--out', skillsDir]);

function readSkill(dir) {
	const text = fs.readFileSync(path.join(dir, 'SKILL.md'), 'utf8');
	const fm = text.match(/^---\n([\s\S]*?)\n---/);
	const fields = {};
	for (const line of fm ? fm[1].split('\n') : []) {
		const m = line.match(/^([a-zA-Z_-]+):\s*(.*)$/);
		if (m) fields[m[1]] = m[2].replace(/^["']|["']$/g, '');
	}
	return fields;
}

const skills = fs.existsSync(skillsDir)
	? fs
			.readdirSync(skillsDir, { withFileTypes: true })
			.filter((d) => d.isDirectory() && fs.existsSync(path.join(skillsDir, d.name, 'SKILL.md')))
			.map((d) => {
				const dir = path.join(skillsDir, d.name);
				const meta = readSkill(dir);
				if (!meta.name || !meta.description) fail(`skills/${d.name}/SKILL.md has no name or description`);
				return {
					name: meta.name,
					description: meta.description,
					url: `${site}/skills/${d.name}/SKILL.md`,
					files: listFiles(dir)
						.map((f) => path.relative(dir, f).split(path.sep).join('/'))
						.sort(),
				};
			})
			.sort((a, b) => a.name.localeCompare(b.name))
	: [];

const wellKnown = path.join(publicDir, '.well-known/agent-skills/index.json');
write(
	wellKnown,
	JSON.stringify(
		{
			name: 'axx',
			description:
				'Agent skills for Axx (github.com/nimbusxr/axx), the human-readable acceptance testing framework. Install them into a repository with `axx skills install`.',
			homepage: site,
			skills,
		},
		null,
		2,
	) + '\n',
);

// ------------------------------------------------- 3. schemas

const schemaV0 = path.join(publicDir, 'schemas/v0/axx.schema.json');
reset(path.join(publicDir, 'schemas'));
fs.mkdirSync(path.dirname(schemaV0), { recursive: true });
log('axx schema');
axx(['schema', '--out', schemaV0]);
// The fixture spec schemas (axx-factory, axx-fixture, axx-prototype) that
// factory files reference with $schema, from `axx docs export`.
for (const f of listFiles(path.join(genDir, 'schemas'), (n) => n.startsWith('axx-') && n.endsWith('.schema.json'))) {
	fs.copyFileSync(f, path.join(path.dirname(schemaV0), path.basename(f)));
}


// ------------------------------------------------- 4. CLI reference

/** Splits cobra help into the long description and the usage block. */
function parseHelp(text) {
	const idx = text.search(/^Usage:\s*$/m);
	const long = idx > 0 ? text.slice(0, idx).trim() : '';
	const usage = idx >= 0 ? text.slice(idx).trimEnd() : text.trimEnd();
	const subcommands = [];
	const block = usage.match(/^Available Commands:\n((?:  .+\n?)+)/m);
	if (block) {
		for (const line of block[1].split('\n')) {
			const m = line.match(/^ {2}(\S+)\s+(.*)$/);
			if (m && m[1] !== 'help') subcommands.push({ name: m[1], short: m[2].trim() });
		}
	}
	return { long, usage, subcommands };
}

const root = parseHelp(axx(['--help']));
const order = ['run', 'validate', 'steps', 'explain', 'up', 'down', 'doctor', 'init', 'schema', 'docs', 'mcp', 'skills', 'version', 'completion'];
const commands = [...root.subcommands].sort((a, b) => {
	const ia = order.indexOf(a.name);
	const ib = order.indexOf(b.name);
	return (ia < 0 ? 99 : ia) - (ib < 0 ? 99 : ib) || a.name.localeCompare(b.name);
});

log(`CLI reference (${commands.length} commands)`);
const cliDir = path.join(genDir, 'cli');
commands.forEach((cmd, i) => {
	const help = parseHelp(axx([cmd.name, '--help']));
	let body = `${GENERATED(`\`axx ${cmd.name} --help\``)}\n${escapeProse(help.long || cmd.short)}\n\n\`\`\`text\n${help.usage}\n\`\`\`\n`;
	for (const sub of help.subcommands) {
		const subHelp = parseHelp(axx([cmd.name, sub.name, '--help']));
		body += `\n## axx ${cmd.name} ${sub.name}\n\n${escapeProse(subHelp.long || sub.short)}\n\n\`\`\`text\n${subHelp.usage}\n\`\`\`\n`;
	}
	write(
		path.join(cliDir, `axx-${cmd.name}.md`),
		frontmatter({ title: `axx ${cmd.name}`, description: cmd.short, sidebar: { order: i + 1 } }) + '\n' + body,
	);
});

write(
	path.join(cliDir, 'index.md'),
	frontmatter({
		title: 'CLI reference',
		description: 'Every Axx command and flag, generated from the help text of the installed binary.',
		sidebar: { order: 0, label: 'Overview' },
	}) +
		`\n${GENERATED('`axx --help`')}\n${escapeProse(root.long)}\n\n` +
		`| Command | Purpose |\n|---|---|\n` +
		commands.map((c) => `| [\`axx ${c.name}\`](/references/cli/axx-${c.name}/) | ${escapeProse(c.short).replace(/\|/g, '\\|')} |`).join('\n') +
		`\n\n\`\`\`text\n${root.usage}\n\`\`\`\n\n` +
		`Every command accepts \`--json\` and prints one [JSON envelope](/references/json-output/). ` +
		`Exit codes are listed in [exit codes](/references/error-codes/#exit-codes).\n`,
);

// ------------------------------------------------- 5. error codes and install scripts

// error-codes.md comes from `axx docs export` (the catalog in
// internal/axxerr, which a Go test keeps in sync with the source). Give it a
// line pointing at `axx explain`.
const errorCodesFile = path.join(genDir, 'error-codes.md');
const sortedCodes = fs.existsSync(errorCodesFile)
	? [...fs.readFileSync(errorCodesFile, 'utf8').matchAll(/^### (AXX-E\d{4})$/gm)].map((m) => m[1])
	: [];
log(`error codes (${sortedCodes.length})`);

// The install scripts are served from the site root:
//   curl -fsSL https://axx.nimbusxr.us/install.sh | sh
for (const name of ['install.sh', 'install.ps1']) {
	const src = path.join(repoDir, 'scripts', name);
	if (!fs.existsSync(src)) fail(`scripts/${name} is missing`);
	fs.copyFileSync(src, path.join(publicDir, name));
}

// ------------------------------------------------- 7. publish generated pages at their natural URLs

// references/_gen/steps/mock.md is served as /references/steps/mock/. The page's
// own `slug` front matter says so, which Starlight and the links validator both
// honor.
for (const file of listFiles(genDir, (n) => n.endsWith('.md'))) {
	let text = capitalizeDocsBrand(fs.readFileSync(file, 'utf8'), commands.map((command) => command.name));
	if (text.startsWith('---\n') && !/^slug:/m.test(text.split('\n---')[0])) {
		const rel = path.relative(genDir, file).split(path.sep).join('/').replace(/\.md$/, '').replace(/(^|\/)index$/, '');
		const slug = rel ? `references/${rel}` : 'references';
		text = text.replace(/^---\n/, `---\nslug: ${JSON.stringify(slug)}\n`);
	}
	fs.writeFileSync(file, text);
}

// ------------------------------------------------- 8. never publish empty output

const checks = [
	['step pack pages (references/_gen/steps/*.md)', listFiles(path.join(genDir, 'steps'), (n) => n.endsWith('.md') && n !== 'index.md')],
	['steps overview page', listFiles(path.join(genDir, 'steps'), (n) => n === 'index.md')],
	['step index page', listFiles(genDir, (n) => n === 'step-index.md')],
	['CLI pages (references/_gen/cli/*.md)', listFiles(cliDir, (n) => n.startsWith('axx-') && n.endsWith('.md'))],
	['error codes', sortedCodes],
	['install scripts', listFiles(publicDir, (n) => n === 'install.sh' || n === 'install.ps1')],
	['skills (public/skills/*/SKILL.md)', listFiles(skillsDir, (n) => n === 'SKILL.md')],
	['agent-skills index entries', skills],
	['schemas (public/schemas/v0)', listFiles(path.dirname(schemaV0), (n) => n.endsWith('.json'))],
];
let empty = false;
for (const [what, items] of checks) {
	if (!items.length) {
		console.error(`gen: error: generated ${what} is empty`);
		empty = true;
	}
}
for (const f of [...listFiles(genDir), ...listFiles(skillsDir)]) {
	if (fs.statSync(f).size === 0) {
		console.error(`gen: error: ${path.relative(docsDir, f)} is an empty file`);
		empty = true;
	}
}
if (fs.existsSync(schemaV0)) {
	try {
		JSON.parse(fs.readFileSync(schemaV0, 'utf8'));
	} catch {
		console.error('gen: error: public/schemas/v0/axx.schema.json is not valid JSON');
		empty = true;
	}
}
if (empty) fail('refusing to build a site with empty generated reference material');

log(
	`ok: ${checks.map(([what, items]) => `${items.length} ${what.split(' (')[0]}`).join(', ')}`,
);
