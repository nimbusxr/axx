// Package manifest records the initial state of a task's project (one
// "sha256  path" line per file, like sha256sum) and compares a project
// against it, so the verifier knows exactly which files the agent added,
// changed or deleted.
package manifest

import (
	"bufio"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"

	"github.com/bmatcuk/doublestar/v4"
)

// Ignored are paths no rule looks at: version control, axx's runtime state,
// agent configuration (skills, MCP, memory) and dependency or build caches.
// They cannot influence what the verifier runs.
var Ignored = []string{
	".git", ".git/**",
	".axx/**",
	".agents/**", ".claude/**", ".codex/**", ".gemini/**", ".cursor/**", ".github/copilot-instructions.md",
	".mcp.json", "AGENTS.md", "CLAUDE.md", "GEMINI.md", ".gitignore", "**/.gitignore",
	"**/node_modules/**", "**/__pycache__/**", "**/.venv/**", "**/.pytest_cache/**",
	"**/.ruff_cache/**", "**/.mypy_cache/**", "**/.DS_Store",
}

// IsIgnored reports whether rel (slash-separated) is ignored.
func IsIgnored(rel string) bool {
	for _, g := range Ignored {
		if ok, _ := doublestar.Match(g, rel); ok {
			return true
		}
	}
	return false
}

// Manifest maps a slash-separated relative path to its content hash.
type Manifest map[string]string

// Hash hashes a file's content (or a symlink's target).
func Hash(p string) (string, error) {
	fi, err := os.Lstat(p)
	if err != nil {
		return "", err
	}
	h := sha256.New()
	if fi.Mode()&fs.ModeSymlink != 0 {
		t, err := os.Readlink(p)
		if err != nil {
			return "", err
		}
		h.Write([]byte("symlink:" + t))
		return hex.EncodeToString(h.Sum(nil)), nil
	}
	f, err := os.Open(p)
	if err != nil {
		return "", err
	}
	defer f.Close()
	if _, err := io.Copy(h, f); err != nil {
		return "", err
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

// Scan hashes every file under root that is not ignored.
func Scan(root string) (Manifest, error) {
	m := Manifest{}
	err := Add(m, root, "")
	return m, err
}

// Add hashes the files under dir into m, with prefix prepended to their paths.
func Add(m Manifest, dir, prefix string) error {
	return filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(dir, p)
		if err != nil {
			return err
		}
		if rel == "." {
			return nil
		}
		rel = path.Join(prefix, filepath.ToSlash(rel))
		if d.IsDir() {
			if IsIgnored(rel) || IsIgnored(rel+"/x") {
				return filepath.SkipDir
			}
			return nil
		}
		if IsIgnored(rel) {
			return nil
		}
		h, err := Hash(p)
		if err != nil {
			return err
		}
		m[rel] = h
		return nil
	})
}

// Read parses a manifest file.
func Read(p string) (Manifest, error) {
	f, err := os.Open(p)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	m := Manifest{}
	sc := bufio.NewScanner(f)
	for n := 1; sc.Scan(); n++ {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		hash, rel, ok := strings.Cut(line, "  ")
		if !ok || len(hash) != 64 {
			return nil, fmt.Errorf("%s:%d: want \"<sha256>  <path>\"", p, n)
		}
		m[rel] = hash
	}
	return m, sc.Err()
}

// Bytes renders the manifest in sha256sum format, sorted by path.
func (m Manifest) Bytes() []byte {
	paths := make([]string, 0, len(m))
	for p := range m {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	var b strings.Builder
	b.WriteString("# Initial project state for the verifier (generated by `go run ./cmd/evals sync`; do not edit).\n")
	for _, p := range paths {
		fmt.Fprintf(&b, "%s  %s\n", m[p], p)
	}
	return []byte(b.String())
}

// Change is one difference between the initial and the current project.
type Change struct {
	Path string `json:"path"`
	Kind string `json:"kind"` // added | modified | deleted
}

// Diff compares current against the initial manifest.
func Diff(initial, current Manifest) []Change {
	var out []Change
	for p, h := range current {
		switch ih, ok := initial[p]; {
		case !ok:
			out = append(out, Change{p, "added"})
		case ih != h:
			out = append(out, Change{p, "modified"})
		}
	}
	for p := range initial {
		if _, ok := current[p]; !ok {
			out = append(out, Change{p, "deleted"})
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Path < out[j].Path })
	return out
}
