const oracleImage = "gvenzl/oracle-free:23-slim-faststart"

// oracleDB starts a real Oracle Database Free for the test, with the statements run.
func oracleDB(t *testing.T, statements ...string) (h *harness, tgt Target, host, port string) {
	t.Helper()
	host, port = container(t, oracleImage, "1521",
		map[string]string{"ORACLE_PASSWORD": "Parcels-Secret-1", "APP_USER": "parcels", "APP_USER_PASSWORD": "Parcels-Secret-1"},
		"DATABASE IS READY TO USE!", 1)
	url := fmt.Sprintf("oracle://%s:%s/FREEPDB1", host, port)
	tgt, err := Resolve(url, "parcels", "Parcels-Secret-1")
	if err != nil {
		t.Fatal(err)
	}
	exec(t, "oracle", tgt.DSN, statements...)
	h = newHarness(t)
	h.ok("a parcels-db database with the following properties:", []string{"url", url}, []string{"user", "parcels"}, []string{"password", "Parcels-Secret-1"})
	return h, tgt, host, port
}

func TestOracle(t *testing.T) {
	h, tgt, host, port := oracleDB(t,
		`CREATE TABLE pickups (
			reference VARCHAR2(40) PRIMARY KEY, postcode VARCHAR2(10), code CHAR(5), shop NVARCHAR2(20), note CLOB,
			grams NUMBER(10), label NUMBER(19,0), tries INTEGER, kilos NUMBER(10,2), rate BINARY_DOUBLE, ratio BINARY_FLOAT, fee FLOAT,
			anything NUMBER, signed_for NUMBER(1), day DATE, planned_at TIMESTAMP, zoned_at TIMESTAMP WITH TIME ZONE, details VARCHAR2(400))`,
		`CREATE TABLE seeded (id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reference VARCHAR2(40), kilos NUMBER(10,2), flagged NUMBER(1), day DATE,
			planned_at TIMESTAMP, zoned_at TIMESTAMP WITH TIME ZONE, created_at TIMESTAMP)`,
		`CREATE TABLE always_id (id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY, reference VARCHAR2(40))`,
		`CREATE TABLE parcels (id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reference VARCHAR2(40) UNIQUE, status VARCHAR2(20), kilos NUMBER(10,2))`,
		`INSERT INTO pickups (reference, postcode, code, shop, grams, label, tries, kilos, rate, ratio, fee, anything, signed_for, day, planned_at, details) VALUES
			('PX-TYPES-1', '10115', 'H91E2', 'willow', 850, 3000000000, 2, 2.00, 1.5, 0.5, 1.5, 7, 1, DATE '2026-09-24', TIMESTAMP '2026-09-24 07:40:00', '{"zone":"DE-1","count":3}')`,
		`INSERT INTO pickups (reference, grams) VALUES ('ABC-OTHER', 1)`,
	)

	t.Run("a JDBC URL and a SID reach the same database", func(t *testing.T) {
		for _, url := range []string{
			fmt.Sprintf("jdbc:oracle:thin:@//%s:%s/FREEPDB1", host, port),
			fmt.Sprintf("jdbc:oracle:thin:@%s:%s:FREE", host, port),
		} {
			tgt, err := Resolve(url, "system", "Parcels-Secret-1")
			if err != nil {
				t.Fatal(err)
			}
			exec(t, "oracle", tgt.DSN, "SELECT 1 FROM dual")
		}
	})

	t.Run("values are held to their columns", func(t *testing.T) {
		columnCases{
			table: "pickups",
			fails: [][3]string{
				{"reference", "0", `reference is text in pickups (VARCHAR2): write "0"`},
				{"postcode", "10115", `postcode is text in pickups (VARCHAR2): write "10115"`},
				{"code", "12345", `code is text in pickups (CHAR): write "12345"`},
				{"shop", "true", `shop is text in pickups (NVARCHAR2): write "true"`},
				{"grams", `"850"`, `grams is an integer in pickups (NUMBER(10,0)): write 850`},
				{"grams", "850.0", `grams is an integer in pickups (NUMBER(10,0)): write 850`},
				{"label", "3000000000.0", `label is an integer in pickups (NUMBER(19,0)): write 3000000000`},
				{"tries", "true", `tries is an integer in pickups (NUMBER(*,0))`},
				{"kilos", "2", `kilos is a decimal in pickups (NUMBER(10,2)): write 2.0`},
				{"fee", "2", `fee is a decimal in pickups (FLOAT)`},
				{"rate", "2", `rate is a decimal in pickups (BINARY_DOUBLE)`},
				{"ratio", "1", `ratio is a decimal in pickups (BINARY_FLOAT)`},
				{"signed_for", "true", `signed_for is an integer in pickups (NUMBER(1,0))`},
				{"day", "2026", `day is written as a string in pickups (DATE): write "2026"`},
				{"postcode", `""`, `Oracle stores an empty string as null`},
			},
			finds: [][2]string{
				{"reference", "PX-TYPES-1"},
				{"postcode", `"10115"`},
				{"shop", "willow"},
				{"grams", "850"},
				{"label", "3000000000"},
				{"tries", "2"},
				{"kilos", "2.0"},
				{"kilos", "2.00"},
				{"rate", "1.5"},
				{"ratio", "0.5"},
				{"fee", "1.5"},
				{"anything", "7"},
				{"signed_for", "1"},
				{"day", `"2026-09-24"`},
				{"day", `"2026-09-24 00:00:00"`},
				{"planned_at", `"2026-09-24 07:40:00"`},
				{"planned_at", `"2026-09-24T07:40:00"`},
			},
			misses: [][2]string{{"reference", "PX-NONE"}, {"grams", "1000"}, {"kilos", "3.0"}, {"postcode", `"99999"`}},
		}.run(t, h, true)
	})

	t.Run("a column with no declared number type is held to what it stores", func(t *testing.T) {
		h.ok("a selection of rows is retrieved from the pickups table where:", []string{"anything", "7.0"})
		svc := mustService(t, h)
		all := svc.Selections()
		if last := all[len(all)-1]; len(last.Rows) != 0 {
			t.Errorf("7.0 selected a row holding 7: %v", last.Rows)
		}
	})

	t.Run("a decimal column gives a decimal, whole or not", func(t *testing.T) {
		h.ok("a selection of rows is retrieved from the pickups table where:", []string{"reference", "PX-TYPES-1"})
		svc := mustService(t, h)
		all := svc.Selections()
		last := all[len(all)-1]
		for column, want := range map[string]string{"kilos": "2.00", "grams": "850", "label": "3000000000"} {
			v, err := last.Value(0, column)
			if err != nil {
				t.Fatal(err)
			}
			if text(v) != want {
				t.Errorf("%s reads as %v (%T), want %s", column, v, v, want)
			}
		}
	})

	t.Run("a column's JSON", func(t *testing.T) {
		h.ok("a selection of rows is retrieved from the pickups table where:", []string{"reference", "PX-TYPES-1"})
		n := nth(len(mustService(t, h).Selections()))
		h.ok(fmt.Sprintf("the 1st row details property for the %s selection json properties are:", n),
			[]string{"zone", "DE-1"}, []string{"count", "3"})
		if err := h.step(fmt.Sprintf("the 1st row details property for the %s selection json properties are:", n), []string{"count", `"3"`}); err == nil {
			t.Error(`"3" matched the number 3`)
		}
	})

	t.Run("a column's value", func(t *testing.T) {
		cellCases{
			table: "pickups",
			passes: [][2]string{
				{"reference", "PX-TYPES-1"},
				{"postcode", `"10115"`},
				{"code", "H91E2"},
				{"grams", "850"},
				{"label", "3000000000"},
				{"tries", "2"},
				{"kilos", "2.0"},
				{"kilos", "2.00"},
				{"rate", "1.5"},
				{"ratio", "0.5"},
				{"fee", "1.5"},
				{"anything", "7"},
				{"signed_for", "1"},
				{"day", "2026-09-24"},
				{"planned_at", "2026-09-24 07:40:00"},
				{"zoned_at", "null"},
				{"note", "null"},
			},
			fails: [][3]string{
				{"postcode", "10115", `"10115"`},
				{"grams", `"850"`, "850"},
				{"kilos", "2", "differs"},
				{"anything", "7.0", "differs"},
				{"day", "2026-09-25", "differs"},
				{"signed_for", "true", "differs"},
			},
		}.run(t, h)
	})

	t.Run("seeds", func(t *testing.T) {
		h.file("seed.yaml", `seeded:
  - id: 7001
    reference: PX-ORA-1
    kilos: 2.5
    flagged: true
    day: "2026-09-24"
    planned_at: "2026-09-24 07:40:00.123"
    zoned_at: "2026-09-24T07:40:00+02:00"
    created_at: "[DAY,PLUS,1]"
  - reference: PX-ORA-2
    kilos: "[null]"
    flagged: false
    zoned_at: "2026-09-24 07:40:00"
    planned_at: "2026-09-24T07:40:00"
`)
		h.ok("a seed.yaml db seed")
		h.ok("a selection of rows is retrieved from the seeded table where:",
			[]string{"id", "7001"}, []string{"reference", "PX-ORA-1"}, []string{"kilos", "2.5"}, []string{"flagged", "1"}, []string{"day", `"2026-09-24"`},
			[]string{"zoned_at", `"2026-09-24T05:40:00Z"`})
		svc := mustService(t, h)
		all := svc.Selections()
		last := all[len(all)-1]
		if len(last.Rows) != 1 {
			t.Fatalf("seeded row: %v", last.Rows)
		}
		created, err := last.Value(0, "created_at")
		if err != nil {
			t.Fatal(err)
		}
		// The machine's wall clock, tomorrow: a TIMESTAMP has no zone to read it by.
		tomorrow := time.Now().AddDate(0, 0, 1).Format("2006-01-02 15")
		if at, ok := created.(time.Time); !ok || at.Format("2006-01-02 15") != tomorrow {
			t.Errorf("created_at: %v (%T), want %s", created, created, tomorrow)
		}
		h.ok("a selection of rows is retrieved from the seeded table where:",
			[]string{"reference", "PX-ORA-2"}, []string{"kilos", "null"}, []string{"flagged", "0"})
		if last := svc.Selections(); len(last[len(last)-1].Rows) != 1 {
			t.Errorf("a row with a null and a false: %v", last[len(last)-1].Rows)
		}
	})

	t.Run("a seed's mistakes say what to write", func(t *testing.T) {
		for _, c := range []struct{ seed, want string }{
			{"seeded:\n  - id: 7001\n    reference: PX-ORA-1\n", "a row with that key is already there"},
			{"seeded:\n  - no_such_column: PX-ORA-3\n", "seeded has the columns ID, REFERENCE"},
			{"seedd:\n  - reference: PX-ORA-3\n", "has the tables"},
			{"always_id:\n  - id: 1\n    reference: PX-ORA-3\n", "GENERATED ALWAYS"},
		} {
			h.file("bad.yaml", c.seed)
			if err := h.step("a bad.yaml db seed"); err == nil || !strings.Contains(err.Error(), c.want) {
				t.Errorf("%q: %v, want %s", c.seed, err, c.want)
			}
		}
	})

	t.Run("row locks", func(t *testing.T) {
		h.ok("the rows in the pickups table are locked where:", []string{"reference", "PX-TYPES-1"})
		db := openForTest(t, tgt)
		ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
		defer cancel()
		if _, err := db.ExecContext(ctx, "SELECT * FROM pickups WHERE reference = 'PX-TYPES-1' FOR UPDATE NOWAIT"); err == nil {
			t.Error("the row is not locked")
		}
		h.ok("the row locks are released")
		if _, err := db.ExecContext(context.Background(), "SELECT * FROM pickups WHERE reference = 'PX-TYPES-1' FOR UPDATE NOWAIT"); err != nil {
			t.Errorf("after releasing: %v", err)
		}
	})

	t.Run("triggers", func(t *testing.T) {
		db := openForTest(t, tgt)
		insert := func(ref string) error {
			_, err := db.Exec("INSERT INTO parcels (reference, status, kilos) VALUES ('" + ref + "', 'REGISTERED', 1.5)")
			return err
		}
		stored := func(ref string) int {
			t.Helper()
			var n int
			if err := db.QueryRow("SELECT COUNT(*) FROM parcels WHERE reference = '" + ref + "'").Scan(&n); err != nil {
				t.Fatal(err)
			}
			return n
		}

		h.ok("a before insert trigger on the parcels table will raise an ORA-20001 exception 1 time where:", []string{"reference", "PX-ORA-T1"})
		if err := insert("PX-ORA-T1"); err == nil || !strings.Contains(err.Error(), "ORA-20001") {
			t.Errorf("the first insert: %v", err)
		}
		if err := insert("PX-ORA-T1"); err != nil {
			t.Errorf("the second insert: %v", err)
		}
		if err := insert("PX-ORA-OTHER"); err != nil {
			t.Errorf("a row it does not match: %v", err)
		}
		h.ok("the before insert trigger on the parcels table was raised 1 time")
		if err := h.step("the before insert trigger on the parcels table was raised 2 times"); err == nil {
			t.Error("a wrong count passed")
		}

		// A number outside RAISE_APPLICATION_ERROR's range, as a deadlock's, by its digits.
		h.ok("a 2nd ordered before insert trigger on the parcels table will raise a 00060 exception where:", []string{"reference", "PX-ORA-T2"}, []string{"status", "REGISTERED"})
		for range 2 {
			if err := insert("PX-ORA-T2"); err == nil || !strings.Contains(err.Error(), "ORA-00060") {
				t.Errorf("a deadlock's number: %v", err)
			}
		}
		if n := stored("PX-ORA-T2"); n != 0 {
			t.Errorf("the failed insert stored %d rows", n)
		}
		h.ok("the 2nd ordered before insert trigger on the parcels table was raised 2 times")

		// The row stays, and the insert fails: a write that succeeded and reported a failure.
		h.ok("a 3rd ordered before insert trigger on the parcels table will insert and raise a 20002 exception where:", []string{"reference", "PX-ORA-T3"})
		if err := insert("PX-ORA-T3"); err == nil || !strings.Contains(err.Error(), "ORA-20002") {
			t.Errorf("insert and raise: %v", err)
		}
		if n := stored("PX-ORA-T3"); n != 1 {
			t.Errorf("insert and raise stored %d rows, want 1", n)
		}
		// Again: a key the row has already is no other failure.
		if err := insert("PX-ORA-T3"); err == nil || !strings.Contains(err.Error(), "ORA-20002") {
			t.Errorf("insert and raise, once more: %v", err)
		}
		h.ok("the 3rd ordered before insert trigger on the parcels table was raised 2 times")

		for _, c := range []struct {
			code string
			rows []string
			want string
		}{
			{"42P01", []string{"reference", "PX-ORA-T4"}, "no Oracle error"},
			{"20001", []string{"kilos", "2"}, "write 2.0"},
			{"20001", []string{"reference", `""`}, "write null"},
		} {
			err := h.step(fmt.Sprintf("a before insert trigger on the parcels table will raise a %s exception where:", c.code), c.rows)
			if err == nil || !strings.Contains(err.Error(), c.want) {
				t.Errorf("%s %v: %v, want %s", c.code, c.rows, err, c.want)
			}
		}

		if err := mustService(t, h).dropTriggers(context.Background()); err != nil {
			t.Fatal(err)
		}
		var left int
		if err := db.QueryRow("SELECT COUNT(*) FROM user_objects WHERE object_name LIKE 'AXX\\_%' ESCAPE '\\'").Scan(&left); err != nil {
			t.Fatal(err)
		}
		if left != 0 {
			t.Errorf("%d of the triggers' objects left", left)
		}
		if err := insert("PX-ORA-T5"); err != nil {
			t.Errorf("after the triggers: %v", err)
		}
	})
}

func openForTest(t *testing.T, tgt Target) *dbsql.DB {
	t.Helper()
	db, err := dbsql.Open("oracle", tgt.DSN)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = db.Close() })
	return db
}
